import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(__dirname, "..");

const geo = JSON.parse(
  readFileSync(resolve(__dirname, "liberia.geojson"), "utf8")
);

// ─── Compute bounding box across all features ─────────────────────────────
let minLon = Infinity;
let maxLon = -Infinity;
let minLat = Infinity;
let maxLat = -Infinity;

for (const f of geo.features) {
  const rings =
    f.geometry.type === "Polygon"
      ? f.geometry.coordinates
      : f.geometry.coordinates.flat();
  for (const ring of rings) {
    for (const [lon, lat] of ring) {
      if (lon < minLon) minLon = lon;
      if (lon > maxLon) maxLon = lon;
      if (lat < minLat) minLat = lat;
      if (lat > maxLat) maxLat = lat;
    }
  }
}

// ─── Projection: fit into 800×520 viewBox with padding ────────────────────
const VB_W = 800;
const VB_H = 520;
const PAD = 20;

const lonSpan = maxLon - minLon;
const latSpan = maxLat - minLat;

// Mercator-lite: at Liberia's latitude the difference is negligible; use
// equirectangular projection scaled uniformly to preserve aspect.
const scaleX = (VB_W - PAD * 2) / lonSpan;
const scaleY = (VB_H - PAD * 2) / latSpan;
const scale = Math.min(scaleX, scaleY);

const usedW = lonSpan * scale;
const usedH = latSpan * scale;
const offsetX = PAD + (VB_W - PAD * 2 - usedW) / 2;
const offsetY = PAD + (VB_H - PAD * 2 - usedH) / 2;

function project(lon, lat) {
  const x = offsetX + (lon - minLon) * scale;
  const y = offsetY + (maxLat - lat) * scale; // flip Y (screen coords)
  return [x, y];
}

// ─── Douglas–Peucker simplification ───────────────────────────────────────
function distToSegmentSq(p, a, b) {
  const dx = b[0] - a[0];
  const dy = b[1] - a[1];
  if (dx === 0 && dy === 0) {
    const ex = p[0] - a[0];
    const ey = p[1] - a[1];
    return ex * ex + ey * ey;
  }
  const t = ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / (dx * dx + dy * dy);
  const tc = Math.max(0, Math.min(1, t));
  const projX = a[0] + tc * dx;
  const projY = a[1] + tc * dy;
  const ex = p[0] - projX;
  const ey = p[1] - projY;
  return ex * ex + ey * ey;
}

function simplify(points, tolerance) {
  if (points.length <= 2) return points;
  const tolSq = tolerance * tolerance;
  const keep = new Array(points.length).fill(false);
  keep[0] = true;
  keep[points.length - 1] = true;

  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [start, end] = stack.pop();
    let maxDistSq = 0;
    let index = start;
    for (let i = start + 1; i < end; i++) {
      const d = distToSegmentSq(points[i], points[start], points[end]);
      if (d > maxDistSq) {
        maxDistSq = d;
        index = i;
      }
    }
    if (maxDistSq > tolSq) {
      keep[index] = true;
      stack.push([start, index]);
      stack.push([index, end]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

// ─── Build SVG paths per county ───────────────────────────────────────────
const TOLERANCE = 0.6; // px in SVG units
const output = geo.features
  .map((f) => {
    const rings =
      f.geometry.type === "Polygon"
        ? f.geometry.coordinates
        : f.geometry.coordinates.flatMap((poly) => poly);

    const parts = rings.map((ring) => {
      const projected = ring.map(([lon, lat]) => project(lon, lat));
      const simplified = simplify(projected, TOLERANCE);
      return simplified
        .map((p, i) => `${i === 0 ? "M" : "L"}${p[0].toFixed(1)},${p[1].toFixed(1)}`)
        .join("") + "Z";
    });

    return {
      name: f.properties.name,
      path: parts.join(""),
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

// ─── Also compute centroids for label/marker placement ────────────────────
function centroid(rings) {
  let sx = 0;
  let sy = 0;
  let n = 0;
  for (const ring of rings) {
    for (const [lon, lat] of ring) {
      const [x, y] = project(lon, lat);
      sx += x;
      sy += y;
      n++;
    }
  }
  return [sx / n, sy / n];
}

const centroids = geo.features.reduce((acc, f) => {
  const rings =
    f.geometry.type === "Polygon"
      ? f.geometry.coordinates
      : f.geometry.coordinates.flatMap((poly) => poly);
  acc[f.properties.name] = centroid(rings).map((v) => Number(v.toFixed(1)));
  return acc;
}, {});

// ─── Emit TypeScript file ─────────────────────────────────────────────────
const outLines = [
  "// Auto-generated by scripts/build-liberia-map.mjs — do not hand-edit.",
  "// Source: click_that_hood/liberia.geojson (public domain OSM-derived).",
  "",
  "export const VIEWBOX = { width: 800, height: 520 };",
  "",
  "export type CountyPath = { name: string; path: string; centroid: [number, number] };",
  "",
  "export const COUNTIES: CountyPath[] = [",
];
for (const c of output) {
  const [cx, cy] = centroids[c.name];
  outLines.push(
    `  { name: ${JSON.stringify(c.name)}, path: ${JSON.stringify(c.path)}, centroid: [${cx}, ${cy}] },`
  );
}
outLines.push("];", "");

const outPath = resolve(projectRoot, "src/data/liberia-map.ts");
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, outLines.join("\n"));

const totalChars = output.reduce((s, c) => s + c.path.length, 0);
console.log(
  `Generated ${output.length} counties, ~${(totalChars / 1024).toFixed(1)}KB of path data at ${outPath}`
);
